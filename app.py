"""Streamlit dashboard: scan an exported AWS config and rank the findings."""
import time
from pathlib import Path

import pandas as pd
import plotly.express as px
import streamlit as st

from scanner.engine import SEVERITY_ORDER, scan
from scanner.parser import load_config, parse_text
from scanner.remediation import get_remediation

SEVERITIES = ["Critical", "High", "Medium", "Low"]
COLORS = {"Critical": "#b42318", "High": "#e8590c", "Medium": "#d4a017", "Low": "#4c78a8"}

st.set_page_config(page_title="Cloud Misconfiguration Scanner", layout="wide")
st.title("Cloud Misconfiguration Scanner")
st.caption("Scans an exported AWS configuration and ranks findings by severity. "
           "Detection and severity come from fixed rules; AI only explains the fix.")

# ---------- input ----------
with st.sidebar:
    st.header("Configuration")
    source = st.radio("Source", ["Sample config", "Upload file"])
    config, label = None, ""
    try:
        if source == "Sample config":
            files = sorted(p.name for p in Path("sample_configs").glob("*")
                           if p.suffix in (".json", ".yaml", ".yml") and p.name != "ground_truth.json")
            choice = st.selectbox("Choose a sample", files)
            config, label = load_config(Path("sample_configs") / choice), choice
        else:
            up = st.file_uploader("JSON or YAML config", type=["json", "yaml", "yml"])
            if up is not None:
                config = parse_text(up.getvalue().decode("utf-8"), Path(up.name).suffix, up.name)
                label = up.name
    except (ValueError, UnicodeDecodeError) as e:
        st.error(str(e))

if config is None:
    st.info("Choose a sample or upload a configuration file to start.")
    st.stop()

# ---------- scan ----------
t0 = time.perf_counter()
findings = scan(config)
scan_ms = (time.perf_counter() - t0) * 1000
df = pd.DataFrame(findings)

st.subheader(f"Results for {label}")
counts = {s: sum(1 for f in findings if f["severity"] == s) for s in SEVERITIES}
cols = st.columns(6)
cols[0].metric("Total findings", len(findings))
for col, s in zip(cols[1:5], SEVERITIES):
    col.metric(s, counts[s])
cols[5].metric("Scan time", f"{scan_ms:.2f} ms")

if df.empty:
    st.success("No misconfigurations found by the current rule set.")
    st.stop()

# ---------- charts ----------
c1, c2 = st.columns(2)
sev_df = pd.DataFrame({"Severity": SEVERITIES, "Findings": [counts[s] for s in SEVERITIES]})
fig1 = px.bar(sev_df, x="Severity", y="Findings", color="Severity", color_discrete_map=COLORS,
              title="Findings by severity")
fig1.update_layout(showlegend=False, margin=dict(t=50, b=10))
c1.plotly_chart(fig1, width="stretch")

cat_df = df.groupby(["category", "severity"]).size().reset_index(name="Findings")
fig2 = px.bar(cat_df, x="category", y="Findings", color="severity", color_discrete_map=COLORS,
              category_orders={"severity": SEVERITIES}, title="Findings by category")
fig2.update_layout(xaxis_title="Category", legend_title="Severity", margin=dict(t=50, b=10))
c2.plotly_chart(fig2, width="stretch")

# ---------- filters + table ----------
f1, f2 = st.columns(2)
sev_sel = f1.multiselect("Severity", SEVERITIES, default=SEVERITIES)
cat_sel = f2.multiselect("Category", sorted(df["category"].unique()), default=sorted(df["category"].unique()))
view = df[df["severity"].isin(sev_sel) & df["category"].isin(cat_sel)]

st.dataframe(
    view[["severity", "rule_id", "resource", "title", "category", "cis", "nist", "waf"]]
    .rename(columns={"severity": "Severity", "rule_id": "Rule", "resource": "Resource",
                     "title": "Issue", "category": "Category", "cis": "CIS",
                     "nist": "NIST CSF 2.0", "waf": "Well-Architected"}),
    width="stretch", hide_index=True,
)
st.download_button("Download findings (CSV)", view.to_csv(index=False).encode("utf-8"),
                   file_name="findings.csv", mime="text/csv")

# ---------- details + AI remediation ----------
st.subheader("Finding details")
for i, f in enumerate(view.to_dict("records")):
    with st.expander(f"[{f['severity']}] {f['rule_id']} - {f['resource']} - {f['title']}"):
        st.write(f["description"])
        st.markdown(f"**CIS:** {f['cis']}  |  **NIST CSF 2.0:** {f['nist']}  |  **Well-Architected:** {f['waf']}")
        key = f"rem_{f['rule_id']}"
        if st.button("Generate AI remediation", key=f"btn_{i}"):
            with st.spinner("Asking the AI..."):
                st.session_state[key] = get_remediation(f)
        if key in st.session_state:
            text, source_tag = st.session_state[key]
            st.text(text)
            st.caption({"ai": "Generated by AI", "cache": "AI answer (cached)",
                        "fallback": "AI unavailable - showing fallback"}[source_tag])
